/**
 * Idempotent one-shot seed: read existing /opt/geniuz/.env values and
 * create one `integration` row per catalog slug.
 *
 *   - Generates INTEGRATION_ENCRYPTION_KEY in .env if missing (32-byte hex)
 *   - For each slug, creates a row with config_public + (encrypted) config_secret
 *     populated from env vars per the catalog's env_map_*
 *   - Sets enabled=true when at least one secret env var is present (or, for
 *     no-secret integrations like GTM/Clarity, when the public ID is set)
 *   - Skips slugs that already have a row in DB (re-run safe)
 *
 * Run: npx medusa exec src/scripts/seed-integrations-from-env.ts
 */

import fs from "node:fs"
import path from "node:path"
import { ExecArgs } from "@medusajs/framework/types"
import { INTEGRATION_MODULE } from "../modules/integration"
import { INTEGRATIONS } from "../modules/integration/catalog"
import { encryptJson, generateMasterKey } from "../lib/integration-crypto"

const ENV_PATH = process.env.MEDUSA_ENV_PATH || path.resolve(process.cwd(), ".env")

function ensureEncryptionKey(): { generated: boolean; key: string } {
  const existing = process.env.INTEGRATION_ENCRYPTION_KEY
  if (existing && existing.trim().length >= 44) {
    return { generated: false, key: existing.trim() }
  }
  const key = generateMasterKey()
  // Append to .env (with backup) so subsequent restarts pick it up.
  try {
    if (fs.existsSync(ENV_PATH)) {
      const stat = fs.statSync(ENV_PATH)
      fs.copyFileSync(ENV_PATH, `${ENV_PATH}.bak-${stat.mtime.getTime()}`)
    }
    const line = `\n# Integration secrets master key (AES-256-GCM). Do not commit. Generated by seed-integrations-from-env.\nINTEGRATION_ENCRYPTION_KEY=${key}\n`
    fs.appendFileSync(ENV_PATH, line, { mode: 0o600 })
  } catch (e: any) {
    // eslint-disable-next-line no-console
    console.warn(`[seed-integrations] failed to persist key to ${ENV_PATH}: ${e?.message}. Set it manually and re-run.`)
  }
  // Crucial: set on the live process so encryptJson() below works in
  // this same exec.
  process.env.INTEGRATION_ENCRYPTION_KEY = key
  return { generated: true, key }
}

export default async function seedIntegrations({ container }: ExecArgs) {
  // eslint-disable-next-line no-console
  console.log("\n=== Seeding integrations from environment ===\n")

  const k = ensureEncryptionKey()
  if (k.generated) {
    console.log(`  ⚙  Generated new INTEGRATION_ENCRYPTION_KEY (32 bytes hex) and persisted to ${ENV_PATH}`)
    console.log("    Future restarts will read it from .env automatically.")
  }

  const svc: any = container.resolve(INTEGRATION_MODULE)
  const existingRows = await svc.listIntegrations({})
  const existingSlugs = new Set<string>(existingRows.map((r: any) => r.slug))

  let created = 0
  let skipped = 0

  for (const def of INTEGRATIONS) {
    if (existingSlugs.has(def.slug)) {
      console.log(`  ↷ ${def.slug.padEnd(22)} already exists, skipping`)
      skipped++
      continue
    }

    const publicCfg: Record<string, string> = {}
    for (const [envKey, fieldKey] of Object.entries(def.env_map_public)) {
      const v = process.env[envKey]
      if (v) publicCfg[fieldKey] = v
    }

    const secretCfg: Record<string, string> = {}
    for (const [envKey, fieldKey] of Object.entries(def.env_map_secret)) {
      const v = process.env[envKey]
      if (v) secretCfg[fieldKey] = v
    }

    const hasSecrets = Object.keys(secretCfg).length > 0
    const hasPublic = Object.keys(publicCfg).length > 0
    // Auto-enable when at least one expected field is present.
    const enabled = (def.secret_fields.length > 0 && hasSecrets) || (def.secret_fields.length === 0 && hasPublic)

    await svc.createIntegrations({
      slug: def.slug,
      name: def.name,
      category: def.category,
      description: def.description,
      logo_path: def.logo_path,
      enabled,
      config_public: publicCfg,
      config_encrypted: hasSecrets ? encryptJson(secretCfg) : null,
      connected_at: enabled ? new Date() : null,
    })

    const pubKeys = Object.keys(publicCfg).join(",") || "—"
    const secKeys = Object.keys(secretCfg).join(",") || "—"
    console.log(`  ✓ ${def.slug.padEnd(22)} enabled=${enabled} | public:${pubKeys} | secret:${secKeys}`)
    created++
  }

  console.log(`\nDone: ${created} created, ${skipped} skipped.\n`)
}
